-- ---------- Modelos de moto ------------------------------------------
-- multiplicador ajusta o preço das peças por modelo (CG = 1,00 base)
create table modelos (
  id            text primary key,
  nome          text not null,
  multiplicador numeric(4,2) not null default 1 check (multiplicador > 0)
);

-- ---------- Catálogo de serviços por peça -----------------------------
-- peca_id deve ser IGUAL ao nome do objeto no modelo 3D (.glb)
create table catalogo (
  id         bigint generated always as identity primary key,
  peca_id    text not null,
  peca_nome  text not null,
  servico    text not null,
  preco      numeric(10,2) not null default 0,  -- preço da peça no modelo base
  horas      numeric(5,2)  not null default 0,  -- tempo de mão de obra
  ativo      boolean not null default true,
  ordem      int not null default 0
);
create index catalogo_peca_idx on catalogo (peca_id);

-- ---------- Clientes e motos ------------------------------------------
create table clientes (
  id         uuid primary key default gen_random_uuid(),
  nome       text not null,
  telefone   text,
  created_at timestamptz not null default now()
);

create table motos (
  id         uuid primary key default gen_random_uuid(),
  cliente_id uuid not null references clientes(id) on delete cascade,
  placa      text not null unique,             -- sempre sem traço, maiúscula
  modelo_id  text not null references modelos(id),
  km         int,
  created_at timestamptz not null default now()
);

-- ---------- Ordens de serviço -----------------------------------------
create table ordens_servico (
  id          bigint generated by default as identity (start with 1041) primary key,
  cliente_id  uuid not null references clientes(id),
  moto_id     uuid not null references motos(id),
  status      text not null default 'Aguardando aprovação'
              check (status in ('Aguardando aprovação','Aprovado','Em execução','Pronto','Entregue','Recusado')),
  km          int,
  valor_hora  numeric(10,2) not null,
  total_pecas numeric(10,2) not null default 0,
  total_mo    numeric(10,2) not null default 0,
  desloc_km       numeric(8,1)  not null default 0 check (desloc_km >= 0),       -- deslocamento: distância
  desloc_valor_km numeric(10,2) not null default 0 check (desloc_valor_km >= 0), -- deslocamento: R$ por km
  total_desloc numeric(10,2) generated always as (round(desloc_km * desloc_valor_km, 2)) stored,
  total       numeric(10,2) generated always as (total_pecas + total_mo + round(desloc_km * desloc_valor_km, 2)) stored,
  criado_por  uuid default auth.uid() references auth.users(id),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- Itens guardam uma "foto" do preço no momento do orçamento,
-- assim mudar o catálogo depois não altera OS antigas.
create table itens_os (
  id          bigint generated always as identity primary key,
  os_id       bigint not null references ordens_servico(id) on delete cascade,
  catalogo_id bigint references catalogo(id),
  peca_nome   text not null,
  servico     text not null,
  qtd         int not null default 1 check (qtd > 0),
  preco_unit  numeric(10,2) not null,
  horas       numeric(5,2)  not null,
  valor_hora  numeric(10,2) not null
);
create index itens_os_idx on itens_os (os_id);

-- updated_at automático
create function set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
create trigger os_updated before update on ordens_servico
  for each row execute function set_updated_at();

-- ---------- Criar OS numa única operação ------------------------------
-- Cadastra/atualiza cliente e moto pela placa, cria a OS e os itens.
-- Os preços são calculados AQUI, a partir do catálogo (não confia no navegador).
create function criar_os(
  p_cliente text, p_telefone text, p_placa text, p_modelo text,
  p_km int, p_valor_hora numeric, p_itens jsonb,  -- [{"catalogo_id":1,"qtd":1}, ...]
  p_desloc_km numeric default 0, p_desloc_valor_km numeric default 0
) returns bigint language plpgsql security invoker as $$
declare
  v_cli uuid; v_moto uuid; v_mult numeric; v_os bigint; v_pc numeric; v_mo numeric;
begin
  p_placa := upper(regexp_replace(coalesce(p_placa,''), '[^A-Za-z0-9]', '', 'g'));
  if p_placa = '' then raise exception 'Informe a placa'; end if;
  if coalesce(trim(p_cliente),'') = '' then raise exception 'Informe o cliente'; end if;
  p_itens := coalesce(p_itens, '[]'::jsonb);
  p_desloc_km := greatest(coalesce(p_desloc_km, 0), 0);
  p_desloc_valor_km := greatest(coalesce(p_desloc_valor_km, 0), 0);
  if jsonb_array_length(p_itens) = 0 and p_desloc_km * p_desloc_valor_km = 0 then
    raise exception 'Orçamento sem itens';
  end if;

  select multiplicador into v_mult from modelos where id = p_modelo;
  if v_mult is null then raise exception 'Modelo inválido'; end if;

  select id, cliente_id into v_moto, v_cli from motos where placa = p_placa;
  if v_moto is null then
    insert into clientes (nome, telefone) values (trim(p_cliente), nullif(trim(p_telefone),''))
      returning id into v_cli;
    insert into motos (cliente_id, placa, modelo_id, km) values (v_cli, p_placa, p_modelo, p_km)
      returning id into v_moto;
  else
    update clientes set nome = trim(p_cliente),
                        telefone = coalesce(nullif(trim(p_telefone),''), telefone)
      where id = v_cli;
    update motos set modelo_id = p_modelo, km = coalesce(p_km, km) where id = v_moto;
  end if;

  insert into ordens_servico (cliente_id, moto_id, km, valor_hora, desloc_km, desloc_valor_km)
    values (v_cli, v_moto, p_km, p_valor_hora, p_desloc_km, p_desloc_valor_km) returning id into v_os;

  insert into itens_os (os_id, catalogo_id, peca_nome, servico, qtd, preco_unit, horas, valor_hora)
  select v_os, c.id, c.peca_nome, c.servico, greatest((i->>'qtd')::int, 1),
         round(c.preco * v_mult, 2), c.horas, p_valor_hora
  from jsonb_array_elements(p_itens) i
  join catalogo c on c.id = (i->>'catalogo_id')::bigint and c.ativo;

  select coalesce(sum(qtd * preco_unit), 0), coalesce(sum(qtd * horas * valor_hora), 0)
    into v_pc, v_mo from itens_os where os_id = v_os;
  update ordens_servico set total_pecas = v_pc, total_mo = round(v_mo, 2) where id = v_os;

  return v_os;
end $$;

-- ---------- Segurança: só a equipe logada acessa ----------------------
alter table modelos        enable row level security;
alter table catalogo       enable row level security;
alter table clientes       enable row level security;
alter table motos          enable row level security;
alter table ordens_servico enable row level security;
alter table itens_os       enable row level security;

create policy equipe on modelos        for all to authenticated using (true) with check (true);
create policy equipe on catalogo       for all to authenticated using (true) with check (true);
create policy equipe on clientes       for all to authenticated using (true) with check (true);
create policy equipe on motos          for all to authenticated using (true) with check (true);
create policy equipe on ordens_servico for all to authenticated using (true) with check (true);
create policy equipe on itens_os       for all to authenticated using (true) with check (true);

-- Projetos novos do Supabase não liberam as tabelas automaticamente: libera só para a equipe logada
grant usage on schema public to authenticated;
grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;

revoke execute on function criar_os from anon, public;
grant  execute on function criar_os to authenticated;

-- Atualização em tempo real da lista de OS (balcão e oficina veem juntos)
alter publication supabase_realtime add table ordens_servico;

